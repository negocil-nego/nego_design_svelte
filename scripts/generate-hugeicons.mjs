import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const assetsDir = path.join(repoRoot, "src/lib/assets/hugeicons");
const outputFile = path.join(repoRoot, "src/lib/components/ui/image/hugeicons.ts");

const suffix = "-stroke-rounded.svg";

const files = (await readdir(assetsDir))
	.filter((f) => f.endsWith(suffix))
	.sort((a, b) => a.localeCompare(b, "en", { numeric: true }));

const entries = {};
for (const file of files) {
	const svg = await readFile(path.join(assetsDir, file));
	const key = file.slice(0, -suffix.length);
	const dataUri = `data:image/svg+xml;base64,${svg.toString("base64")}`;
	entries[key] = dataUri;
}

entries["chevron-down"] = entries["chevron-right"];

const lines = [
	"/**",
	" * Ícones Hugeicons embutidos como data URIs (SVG locais em src/lib/assets/hugeicons).",
	" * Remove a dependência de @hugeicons/core-free-icons e @hugeicons/svelte.",
	" * Generated by `npm run generate:hugeicons` — não edite manualmente.",
	" */"
];
lines.push("export const hugeicons = {");
for (const [key, dataUri] of Object.entries(entries)) {
	lines.push(`   "${key}": "${dataUri}",`);
}
lines.push("} as const;");
lines.push("export type HugeiconsIconName = keyof typeof hugeicons;");
lines.push("");

await writeFile(outputFile, lines.join("\n"), "utf-8");
console.log(`Generated ${Object.keys(entries).length} hugeicons in ${outputFile}`);