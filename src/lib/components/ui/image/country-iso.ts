/** Mapa reverso: código ISO (2 letras, minúsculas) → constante do enum do backend. */
export const ISO_TO_NAME: Record<string, string> = Object.fromEntries(
  Object.entries(COUNTRY_ISO).map(([name, iso]) => [iso, name]),
);

/** Converte a constante do enum do backend num código ISO de 2 letras (ex: "ANGOLA" → "ao"). */
export const countryIso = (country?: string): string | undefined =>
  country ? COUNTRY_ISO[country] : undefined;

/** Converte um código ISO de 2 letras na constante do enum do backend (ex: "ao" → "ANGOLA"). */
export const countryNameByIso = (iso?: string): string | undefined =>
  iso ? ISO_TO_NAME[iso] : undefined;